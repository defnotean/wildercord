SLOTS = ["FIRST", "SECOND", "THIRD", "FOURTH", "FINAL"]


def _string_consts():
    """{class name: {CONST: "value"}} for every `static final String X = "y"` in the source, so a constant id resolves."""
    out = {}
    for p in JAVA.rglob("*.java"):
        src = p.read_text(encoding="utf-8", errors="replace")
        out[p.stem] = dict(re.findall(r'static\s+final\s+String\s+(\w+)\s*=\s*"([\w:]+)"', src))
    return out


def _resolve(ref, src, here, consts):
    """A string literal, a Class.CONST, or a CONST from this file or a static import, as its value; None if unknown."""
    ref = ref.strip()
    if ref.startswith('"'):
        return ref.strip('"')
    if "." in ref:
        cls, name = ref.rsplit(".", 1)
        return consts.get(cls.rsplit(".", 1)[-1], {}).get(name)
    if ref in consts.get(here, {}):
        return consts[here][ref]
    for cls in re.findall(r"import\s+static\s+[\w.]*?\.(\w+)\.(?:\*|" + re.escape(ref) + r")\s*;", src):
        if ref in consts.get(cls, {}):
            return consts[cls][ref]
    return None


def read_methods():
    """Every `new BreathingMethod(id, "element", ...)` in the source, in file order (BreathingMethods.java first). The id may be a
    literal or a constant (Echo, Dawn and Venom use MethodsBArtRules' ids and register outside BUILT_IN)."""
    consts = _string_consts()
    files = [JAVA / "aura/BreathingMethods.java"] + sorted(p for p in JAVA.rglob("*.java") if p.name != "BreathingMethods.java")
    seen, methods = set(), []
    for f in files:
        if not f.exists():
            continue
        src = f.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'new\s+BreathingMethod\(\s*("\w+"|[\w.]+)\s*,\s*"(\w+)"', src):
            mid = _resolve(m.group(1), src, f.stem, consts)
            if mid is None:
                print(f"wiki_reference: skipped a breathing method whose id it couldn't read: {m.group(1)} in {f.name}")
                continue
            if mid not in seen:
                seen.add(mid)
                methods.append({"id": mid, "element": m.group(2)})
    return methods


def read_arts():
    """{method id: [(slot, art id)]} from every *Arts.java that declares METHOD and MethodArts.art(ArtSlot.X, CONST, ...)."""
    consts = _string_consts()
    arts = {}
    for f in sorted((JAVA / "aura").rglob("*Arts.java")):
        src = f.read_text(encoding="utf-8", errors="replace")
        method = re.search(r'\bMETHOD\s*=\s*("\w+"|[\w.]+)\s*;', src)
        if not method:
            continue
        mid = _resolve(method.group(1), src, f.stem, consts)
        if mid is None:
            print(f"wiki_reference: skipped {f.name}: couldn't read its METHOD")
            continue
        found = []
        for slot, ref in re.findall(r"MethodArts\.art\(\s*(?:AuraApi\.)?ArtSlot\.(\w+)\s*,\s*(\w+|\"[\w:]+\")", src):
            art = _resolve(ref, src, f.stem, consts)
            if art:
                found.append((slot, art))
        arts.setdefault(mid, []).extend(found)
    return arts


def read_slot_rules():
    src = (JAVA / "aura/ArtRules.java").read_text(encoding="utf-8")
    cost = re.search(r"SLOT_COST\s*=\s*\{([^}]*)\}", src)
    cool = re.search(r"SLOT_COOLDOWN\s*=\s*\{([^}]*)\}", src)
    costs = [float(x) for x in cost.group(1).split(",")] if cost else []
    cools = [int(x) for x in cool.group(1).split(",")] if cool else []
    api = (JAVA / "api/AuraApi.java").read_text(encoding="utf-8")
    stages = dict(re.findall(r"\b(FIRST|SECOND|THIRD|FOURTH|FINAL)\(\"[^\"]*\",\s*AuraRules\.(\w+)\)", api))
    strings = dict(re.findall(r"\b(FIRST|SECOND|THIRD|FOURTH|FINAL)\(\"([^\"]*)\"", api))
    return costs, cools, stages, strings


STRING_WORDS = {"swing swing low": "swing, swing, low swing", "leap low": "leaping swing, then a low swing",
                "counter": "your first swing after a perfect Aura Guard", "step": "your first swing after an Aura Step",
                "full full full low": "three full swings, then a low swing"}


def methods_page():
    words = lang()
    methods = read_methods()
    arts = read_arts()
    costs, cools, stages, strings = read_slot_rules()
    lines = ["# Breathing methods", "",
             "A **breathing method** is the element your Aura takes. Each one colours your Aura, adds its own touch to your blows, "
             "and gives you five **arts**: special cuts you play by swinging a set pattern with your sword. "
             f"There are {len(methods)} methods. For how to choose and change one, see [Aura]({{{{ '/progression/aura/' | relative_url }}}}).", "",
             "## How arts unlock", "",
             "Every method's arts open at the same Aura stages and use the same swing patterns:", "",
             "| Art | Opens at | Play it with | Aura cost | Rest |", "|---|---|---|---|---|"]
    for i, slot in enumerate(SLOTS):
        stage = words.get(f"aura.wildercord.stage.{stages.get(slot, '').lower()}", titled(stages.get(slot, "")))
        pattern = STRING_WORDS.get(strings.get(slot, ""), strings.get(slot, ""))
        name = words.get(f"aura.wildercord.art.{slot.lower()}_art", titled(slot.lower() + " art"))
        cost = f"{costs[i]:g}" if i < len(costs) else ""
        rest = seconds(cools[i]) if i < len(cools) else ""
        lines.append(f"| {name} | {stage} | {pattern} | {cost} | {rest} |")
    lines += ["", "Some arts set their own cost or rest; the Aura page in game always shows the real numbers.", ""]
    lines += ["| Method | Element |", "|---|---|"]
    for m in methods:
        name = words.get(f"aura.wildercord.method.{m['id']}", titled(m["id"]))
        lines.append(f"| [{name}](#{m['id']}) | {m['element'].title()} |")
    lines.append("")
    for m in methods:
        name = words.get(f"aura.wildercord.method.{m['id']}", titled(m["id"]))
        lines += [f"## {name}", f"{{: #{m['id']}}}", "", f"*{m['element'].title()}*", ""]
        lore = words.get(f"aura.wildercord.method.{m['id']}.lore")
        flavour = words.get(f"aura.wildercord.method.{m['id']}.flavour")
        if lore:
            lines += [f"> {lore}", ""]
        if flavour:
            lines += [flavour, ""]
        own = arts.get(m["id"], [])
        if own:
            lines += ["| Art | Name | What it does |", "|---|---|---|"]
            for slot, art in sorted(own, key=lambda a: SLOTS.index(a[0]) if a[0] in SLOTS else 9):
                key = art.replace(":", ".")
                art_name = words.get(f"aura.wildercord.art.{key}", titled(art.split(":")[-1]))
                desc = words.get(f"aura.wildercord.art.{key}.desc", "")
                slot_name = words.get(f"aura.wildercord.art.{slot.lower()}_art", titled(slot.lower()))
                lines.append(f"| {slot_name} | **{cell(art_name)}** | {cell(desc)} |")
            lines.append("")
        else:
            lines += ["This method plays the five common arts.", ""]
    write(WIKI / "progression/breathing-methods.md",
          {"title": "Breathing Methods", "parent": "Growing Stronger", "nav_order": 2.25}, lines)
    return len(methods)


