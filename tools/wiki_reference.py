"""More of the player wiki's generated reference pages, read from the game's own source so new content shows up by itself:

    wiki/runes/codex.md                  every rune by family and Codex category (spell/RuneCategories.java)
    wiki/progression/breathing-methods.md every breathing method and its five arts (aura/BreathingMethods.java, aura/arts/*)
    wiki/masters/techniques.md           every Sword Master and technique: strikes, shapes, answers, timing, damage, signatures and
                                         first-clear rewards (aura/world/MasterTechniques.java and the pack files it loads)

Called from tools/wiki.py (python tools/wiki.py). Pure Python: it reads the Java and the English lang file and never runs the game.
Anything it can't parse is skipped with a warning rather than guessed.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVA = ROOT / "src/main/java/dev/wildercord"
LANG = ROOT / "src/main/resources/assets/wildercord/lang/en_us.json"
WIKI = ROOT / "wiki"
MARK = "<!-- Generated by tools/wiki.py from the game's own data: edit that, not this page. -->"


def lang():
    try:
        return json.loads(LANG.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def titled(word):
    return word.replace("_", " ").strip().title()


def roman(n):
    out = ""
    for value, numeral in ((10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I")):
        while n >= value:
            out += numeral
            n -= value
    return out


def seconds(ticks):
    s = ticks / 20
    return f"{s:.2f}".rstrip("0").rstrip(".") + " s"


def write(path, front, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    head = ["---"] + [f"{k}: {v}" for k, v in front.items()] + ["---", "", MARK, ""]
    path.write_text("\n".join(head + lines) + "\n", encoding="utf-8", newline="\n")


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


# ------------------------------------------------------------------ Codex categories

FAMILIES = ["SHAPE", "EFFECT", "MODIFIER", "LINK", "KNOT"]


def read_categories():
    """RuneCategories.java: ({family: [categories in Codex order]}, {family: [(paths, category)]}, {family: default},
    {family: [(suffix, category)]}). Any list, case or suffix test someone adds is picked up."""
    src = (JAVA / "spell/RuneCategories.java").read_text(encoding="utf-8")
    order = {}
    for fam in FAMILIES:
        m = re.search(rf"\b{fam}\s*=\s*List\.of\((.*?)\);", src, re.S)
        order[fam] = re.findall(r'"(\w+)"', m.group(1)) if m else []
    for fam, cat in re.findall(r"RuneCategories\.add\(\s*RuneFamily\.(\w+)\s*,\s*\"(\w+)\"", _all_java()):
        if cat not in order.setdefault(fam, []):
            order[fam].append(cat)
    body = src[src.find("categoryFor("):]
    # Split the outer switch into one chunk per family.
    starts = [(m.start(), m.group(1)) for m in re.finditer(r"\bcase\s+(SHAPE|EFFECT|MODIFIER|LINK|KNOT)\s*->", body)]
    cases, defaults, suffixes = {}, {}, {}
    for i, (at, fam) in enumerate(starts):
        chunk = body[at:starts[i + 1][0] if i + 1 < len(starts) else len(body)]
        chunk = re.sub(r"//[^\n]*", "", chunk)
        cases[fam] = [(re.findall(r'"(\w+)"', paths), cat)
                      for paths, cat in re.findall(r'case\s+((?:"\w+"\s*,\s*)*"\w+")\s*->\s*"(\w+)"\s*;', chunk, re.S)]
        d = re.search(r'default\s*->\s*"(\w+)"', chunk)
        direct = re.match(r'case\s+\w+\s*->\s*"(\w+)"', chunk)
        defaults[fam] = d.group(1) if d else (direct.group(1) if direct else "")
        suffixes[fam] = re.findall(r'path\.endsWith\("(\w+)"\)\s*\?\s*"(\w+)"', chunk)
    return order, cases, defaults, suffixes


def _all_java():
    return "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in JAVA.rglob("*.java"))


def category(path, family, cases, defaults, suffixes):
    fam = family.upper()
    for suffix, cat in suffixes.get(fam, []):
        if path.endswith(suffix):
            return cat
    for paths, cat in cases.get(fam, []):
        if path in paths:
            return cat
    return defaults.get(fam, "")


CATEGORY_BLURB = {
    ("shape", "personal"): "On you or around you.",
    ("shape", "direct"): "Straight from you to what you aim at, with no flight time.",
    ("shape", "projectile"): "Something that flies and can miss.",
    ("shape", "area"): "Everything in a space at once.",
    ("shape", "lingering"): "Waits on the ground or in the air and works over time.",
}


def codex_page(runes, link_of):
    order, cases, defaults, suffixes = read_categories()
    words = lang()
    lines = ["# Runes by Codex category", "",
             "The Codex in your Cord screen sorts each rune family into categories by what the rune is *for*. "
             "This page uses the same sorting, so you can find, say, every World effect or every Condition link in one place. "
             "Each name links to the rune's full entry.", ""]
    family_title = {"shape": "Shapes", "effect": "Effects", "modifier": "Modifiers", "link": "Links"}
    total = 0
    for family in ("shape", "effect", "modifier", "link"):
        rs = [r for r in runes if r["family"] == family]
        if not rs:
            continue
        groups = {}
        for r in rs:
            groups.setdefault(category(r["path"], family, cases, defaults, suffixes) or "other", []).append(r)
        known = order.get(family.upper(), [])
        cats = [c for c in known if c in groups] + sorted(c for c in groups if c not in known)
        lines += [f"## {family_title[family]}", ""]
        lines += ["| Category | Runes |", "|---|---|"]
        for cat in cats:
            label = words.get(f"category.wildercord.{family}.{cat}", titled(cat))
            lines.append(f"| [{cell(label)}](#{family}-{cat}) | {len(groups[cat])} |")
        lines.append("")
        for cat in cats:
            label = words.get(f"category.wildercord.{family}.{cat}", titled(cat))
            lines += [f"### {label} {family_title[family].lower()}", f"{{: #{family}-{cat}}}", ""]
            if CATEGORY_BLURB.get((family, cat)):
                lines += [CATEGORY_BLURB[(family, cat)], ""]
            items = []
            for r in sorted(groups[cat], key=lambda r: (r["tier"], r["name"])):
                extra = f", {r['element'].title()}" if r.get("element") else ""
                items.append(f"- {link_of(r['path'])} (Tier {roman(r['tier'])}{extra})")
            lines += items + [""]
            total += len(groups[cat])
    lines.insert(4, f"{total} runes in all.")
    lines.insert(5, "")
    write(WIKI / "runes/codex.md", {"title": "By Codex Category", "parent": "Runes", "nav_order": 8}, lines)
    return total


