def _num(expr):
    return float(re.sub(r"[^\d.\-]", "", expr) or 0)


def _src(rel):
    return (JAVA / rel).read_text(encoding="utf-8")


def _ints(src):
    """Every `static final int A = 1, B = 2;` constant in a file."""
    out = {}
    for decl in re.findall(r"static\s+final\s+int\s+([^;]*);", src):
        for name, value in re.findall(r"\b(\w+)\s*=\s*(-?\d+)\b", decl):
            out[name] = int(value)
    return out


def _const(src, name, file):
    m = re.search(rf"\b{name}\s*=\s*([\d.]+)", src)
    if not m:
        raise ValueError(f"wiki_reference: {name} not found in {file}")
    return float(m.group(1))


def _body(src, signature):
    """The body of the first method whose declaration matches `signature` (a regex), up to its closing tab-brace."""
    m = re.search(signature + r"[^{]*\{(.*?)\n\t\}", src, re.S)
    return m.group(1) if m else ""


def read_tables():
    """[(school constant, table text, pack)] in id order: the base three, masters-a, masters-b, methods-a, then methods-b's reserved ids."""
    mt = _src("aura/world/MasterTechniques.java")
    out = [(s, t, "base") for s, t in re.findall(r'school\(\s*MastersRules\.(\w+)\s*,\s*"""(.*?)"""\s*\)', mt, re.S)]
    em = _src("aura/world/ElementalMasters.java")
    order = re.search(r"SCHOOL_IDS\s*=\s*List\.of\(([^)]*)\)", em).group(1)
    em_tables = dict(re.findall(r'case\s+(\w+)\s*->\s*"""(.*?)"""', _body(em, r"static String techniques\(int school\)"), re.S))
    out += [(s.strip(), em_tables[s.strip()], "masters-a") for s in order.split(",") if s.strip() in em_tables]
    pb = _src("aura/world/MastersPackB.java")
    out += [(s, t, "masters-b") for s, t in re.findall(r'table\.add\(\s*(\w+)\s*,\s*"""(.*?)"""\s*\)', pb, re.S)]
    ma = _src("aura/world/MethodsAMasters.java")
    ma_tables = dict(re.findall(r'String\s+(\w+_TABLE)\s*=\s*"""(.*?)"""', ma, re.S))
    out += [(s, ma_tables[t], "methods-a") for s, t in re.findall(r"table\.add\(\s*(\w+)\s*,\s*(\w+_TABLE)\s*\)", ma) if t in ma_tables]
    mb = _src("aura/world/MethodsBMasters.java")
    mb_tables = dict(re.findall(r'String\s+(\w+_TABLE)\s*=\s*"""(.*?)"""', mb, re.S))
    out += [(s, mb_tables[t], "methods-b") for s, t in
            re.findall(r"school\(\s*MethodsBMasters\.(\w+)\s*,\s*MethodsBMasters\.(\w+_TABLE)", mt) if t in mb_tables]
    return out


def read_pack_timing():
    """How each pack re-times what the base formula authors: read from the pack's own tell()/recovery() and constants."""
    mt = _src("aura/world/MasterTechniques.java")
    em = _src("aura/world/ElementalMasters.java")
    e = _ints(em)
    tell_body = _body(em, r"static int tell\(boolean heavy")
    heavy = re.search(r"heavy\s*\?\s*(\d+)\s*:\s*0", tell_body)
    turn = re.search(r"spin\s*\|\|\s*step\s*\?\s*(\d+)\s*:\s*0", tell_body)
    extra = re.search(r"Math\.min\((\d+),\s*count\s*-\s*1\)", em)
    if not (heavy and turn and extra) or "ElementalMasters.tell(" not in mt:
        print("wiki_reference: masters-a's tell rule changed shape; its times may be off")
    timing = {"masters-a": {"kind": "fixed", "min": e["MIN_TELL"], "max": e["MAX_TELL"], "heavy": int(heavy.group(1)) if heavy else 1,
                            "turn": int(turn.group(1)) if turn else 1, "rec": e["MIN_RECOVERY"],
                            "rec_extra": int(extra.group(1)) if extra else 2}}
    for pack, rel, hook in (("masters-b", "aura/world/MastersPackB.java", "MastersPackB"),
                            ("methods-a", "aura/world/MethodsAMasters.java", "MethodsAMasters")):
        src = _src(rel)
        c = _ints(src)
        chain = re.search(r"authored\s*\+\s*\(index\s*==\s*0\s*\?\s*(\d+)\s*:\s*(\d+)\)", src)
        if not chain or f"{hook}.tell(" not in mt:
            print(f"wiki_reference: {pack}'s tell rule changed shape; its times may be off")
        timing[pack] = {"kind": "clamp", "min": c["MIN_TELL"], "max": c["MAX_TELL"], "first": int(chain.group(1)) if chain else 0,
                        "follow": int(chain.group(2)) if chain else 0, "rec_min": c["MIN_RECOVERY"], "rec_max": c["MAX_RECOVERY"]}
    if "MethodsBMasters.tell(" in mt or "MethodsBMasters.recovery(" in mt:
        print("wiki_reference: methods-b now re-times its techniques; teach read_pack_timing() its rule")
    return timing


def read_signatures(words):
    """({school constant: [signature names]}, [methods-b signature technique keys]): single-school moves in MasterMoveCatalog,
    plus the techniques methods-b names as signatures."""
    cat = _src("aura/world/MasterMoveCatalog.java")
    sig = {}
    for move, school in re.findall(r"MastersRules\.Move\.(\w+)\s*,\s*Set\.of\(\s*\w+\.(\w+)\s*\)", cat):
        sig.setdefault(school, []).append(words.get(f"boss.wildercord.master.{move.lower()}", titled(move)))
    mb = _src("aura/world/MethodsBMasters.java")
    block = re.search(r"SIGNATURES\s*=\s*Map\.of\((.*?)\);", mb, re.S)
    keys = re.findall(r'"(\w+)"\s*,\s*MethodsBSignatureRules\.Signature\.\w+', block.group(1)) if block else []
    return sig, keys


def read_rewards(words):
    """{school constant: technique-part name} from MasterVictoryRules.reward and the pack reward() it hands off to."""
    tr = dict(re.findall(r'static\s+final\s+String\s+(\w+)\s*=\s*"(\w+)"', _src("aura/TechniqueRules.java")))
    out = {}
    for rel in ("aura/world/ElementalMasters.java", "aura/world/MethodsAMasters.java", "aura/world/MethodsBMasters.java",
                "aura/world/MasterVictoryRules.java"):
        body = _body(_src(rel), r"static String reward\(int school\)")
        for labels, const in re.findall(r"case\s+([\w.,\s]+?)\s*->\s*[\w.]*TechniqueRules\.(\w+)", body):
            part = tr.get(const, const.lower())
            for label in labels.split(","):
                out.setdefault(label.strip().rsplit(".", 1)[-1], words.get(f"aura.wildercord.technique_part.{part}", titled(part)))
    return out


def read_techniques():
    mt = _src("aura/world/MasterTechniques.java")
