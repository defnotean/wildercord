def parse_mask(text: str) -> set:
    return {(x, y) for y, row in enumerate(grid(text)) for x, ch in enumerate(row) if ch == "#"}


def ring_depth(mask: set) -> dict:
    """4-connected distance of every mask pixel from the outside (0 = outline)."""
    depth = {}
    frontier = [p for p in mask if any((p[0] + dx, p[1] + dy) not in mask for dx, dy in N4)]
    for p in frontier:
        depth[p] = 0
    d = 0
    while frontier:
        d += 1
        nxt = []
        for (x, y) in frontier:
            for dx, dy in N4:
                q = (x + dx, y + dy)
                if q in mask and q not in depth:
                    depth[q] = d
                    nxt.append(q)
        frontier = nxt
    return depth


def centroid(mask):
    xs = [p[0] for p in mask]
    ys = [p[1] for p in mask]
    return (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2


def facing(p, c) -> float:
    """How much a rim pixel faces the light: +1 top-left .. -1 bottom-right."""
    dx, dy = p[0] - c[0], p[1] - c[1]
    ln = math.hypot(dx, dy) or 1
    return (dx * LIGHT[0] + dy * LIGHT[1]) / ln


def sector8(p, c) -> int:
    """0 = top, then clockwise: 1 top-right, 2 right ... 7 top-left."""
    ang = math.degrees(math.atan2(p[0] - c[0], -(p[1] - c[1]))) % 360
    return int(((ang + 22.5) % 360) // 45)


# ============================================================== stones


class Stone:
    def __init__(self, canvas, depth, face, rim, glow):
        self.canvas = canvas
        self.face = face          # recessed face pixels
        self.rim = rim            # trim / facet pixels
        self.glow = glow          # pictogram ramp: (shade, main, light, core)
        # pictograms keep one face pixel clear of the trim so they never merge with it
        self.safe = {p for p, d in depth.items() if d >= 3}
        ys = sorted({p[1] for p in self.safe})
        self.box = (ys[0], ys[-1] - ys[0] + 1)      # (top row, row count)


def grey_stone(pal: dict, silhouette: str, rivets=()) -> Stone:
    mask = parse_mask(silhouette)
    depth = ring_depth(mask)
    c = centroid(mask)
    cv = Canvas()
    tr, fc = pal["trim"], pal["face"]
    face, rim = set(), set()
    for p, d in depth.items():
        f = facing(p, c)
        if d == 0:
            col = pal["outline"]
        elif d == 1:
            rim.add(p)
            col = tr[3] if f > 0.72 else tr[2] if f > 0.05 else tr[1] if f > -0.6 else tr[0]
        else:
            face.add(p)
            if d == 2:
                # recessed face: lip shadow top-left, bounced light bottom-right
                col = fc[0] if f > 0.35 else fc[2] if f < -0.55 else fc[1]
            else:
                col = fc[1]
        cv.put(*p, col)
    for p in rivets:        # corner studs pinning the tablet into its frame
        cv.put(*p, tr[2])
    return Stone(cv, depth, face, rim, pal["glow"])


# facet tone (index into the facet ramp) per 8-sector, 0 = top, clockwise
GEM_OUTER = [3, 2, 1, 0, 0, 1, 2, 3]
GEM_INNER = [2, 1, 1, 0, 0, 0, 1, 2]


def gem_stone(element: str) -> Stone:
    pal = ELEMENT.get(element) or ELEMENT["arcane"]
    mask = parse_mask(SILHOUETTE["effect"])
    depth = ring_depth(mask)
    c = centroid(mask)
    cv = Canvas()
    fa, tb = pal["facet"], pal["table"]
    face, rim = set(), set()
    for p, d in depth.items():
        s = sector8(p, c)
        if d == 0:
            col = pal["outline"]
        elif d == 1:
            rim.add(p)
            col = fa[GEM_OUTER[s]]
        elif d == 2:
            rim.add(p)
            col = fa[GEM_INNER[s]]
        else:
            face.add(p)
            col = tb[0] if (d == 3 and facing(p, c) > 0.3) else tb[1]
        cv.put(*p, col)
    return Stone(cv, depth, face, rim, pal["glow"])


def family_stone(family: str, element: str) -> Stone:
    if family == "effect":
        return gem_stone(element)
    fam = family if family in FAMILY else "shape"
    return grey_stone(FAMILY[fam], SILHOUETTE[fam], RIVETS.get(fam, ()))


