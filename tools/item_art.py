def roster():
    """(path, family, element, tier) for every rune, read from Runes.java when it is
    reachable so the review sheet never drifts from the game; ROSTER is the fallback."""
    import re
    from pathlib import Path

    src = Path(__file__).resolve().parent.parent / "src/main/java/dev/wildercord/spell/Runes.java"
    if src.exists():
        out = []
        for m in re.finditer(r'= (shape|effect|modifier|link)\("(\w+)", "[^"]+", (\d), ([^\n]*)\);',
                             src.read_text(encoding="utf-8")):
            fam, path, tier, rest = m.groups()
            el = re.match(r'[\d.]+, "(\w+)"', rest).group(1) if fam == "effect" else ""
            out.append((path, fam, el, int(tier)))
        if len(out) >= 40:
            return out
    out = []
    for chunk in ROSTER.replace("\n", "|").split("|"):
        chunk = chunk.strip()
        if chunk:
            path, fam, el, tier = chunk.split()
            out.append((path, fam, "" if el == "-" else el, int(tier)))
    return out


def _check(frames, name, allow_alpha=False, size=16):
    for im in frames:
        assert im.size == (size, size) and im.mode == "RGBA", name
        if not allow_alpha:
            alphas = set(im.getchannel("A").tobytes())
            assert alphas <= {0, 255}, f"{name}: partial alpha {alphas}"


def preview(out_dir: str):
    from pathlib import Path
    from PIL import ImageDraw

    items = []
    for path, fam, el, tier in roster():
        fr = rune_icon(path, fam, el, tier)
        _check(fr, path)
        items.append((f"{path} t{tier}", fr))
    for name, fr in [("blank", blank_rune_icon()), ("silent", silent_rune_icon())]:
        _check(fr, name)
        items.append((name, fr))
    for k in ["twine", "copper", "amethyst", "echo"]:
        fr = cord_icon(k)
        _check(fr, k)
        items.append((f"cord_{k}", fr))
    slot = cord_slot_icon()
    _check([slot], "slot", allow_alpha=True)
    items.append(("cord_slot", [slot]))
    crystal = mana_crystal_icon()
    _check(crystal, "mana_crystal")
    items.append(("mana_crystal", crystal))
    for name, im, size in [("clarity 18px", clarity_effect_icon(), 18), ("mana 18px", mana_effect_icon(), 18),
                           ("mana_badge 12px", mana_badge_icon(), 12), ("warded 18px", warded_effect_icon(), 18),
                           ("ward_badge 12px", ward_badge_icon(), 12)]:
        _check([im], name, size=size)
        items.append((name, [im]))

    S, cols = 8, 8
    cw, ch = 18 * S + 12, 18 * S + 22
    rows = (len(items) + cols - 1) // cols
    sheet = Image.new("RGBA", (cols * cw + 12, rows * ch + 12), (0x8B, 0x8B, 0x8B, 255))
    d = ImageDraw.Draw(sheet)
    for i, (name, fr) in enumerate(items):
        x = 12 + (i % cols) * cw
        y = 12 + (i // cols) * ch
        w = fr[0].width
        off = (18 - w) * S // 2
        sheet.alpha_composite(fr[0].resize((w * S, w * S), Image.NEAREST), (x + off, y + off))
        label = name + (f" [{len(fr)}f]" if len(fr) > 1 else "")
        d.text((x, y + 18 * S + 3), label, fill=(20, 20, 20, 255))
    Path(out_dir).mkdir(parents=True, exist_ok=True)
    sheet.save(f"{out_dir}/item_art_sheet.png")

    # true 1x strips on inventory grey and on a dark background (upscaled 3x afterwards
    # with nearest-neighbour purely so the image viewer does not smear them)
    per = 16
    srows = (len(items) + per - 1) // per
    band = srows * 20 + 2
    one = Image.new("RGBA", (per * 20 + 2, band * 2), (0x8B, 0x8B, 0x8B, 255))
    one.alpha_composite(Image.new("RGBA", (per * 20 + 2, band), (0x1B, 0x17, 0x26, 255)), (0, band))
    for i, (name, fr) in enumerate(items):
        off = (18 - fr[0].width) // 2
        x = 2 + (i % per) * 20 + off
        y = 2 + (i // per) * 20 + off
        one.alpha_composite(fr[0], (x, y))
        one.alpha_composite(fr[0], (x, y + band))
    one.resize((one.width * 3, one.height * 3), Image.NEAREST).save(f"{out_dir}/item_art_1x.png")

    anim = [(n, fr) for n, fr in items if len(fr) > 1]
    if anim:
        A = 4
        mx = max(len(fr) for _, fr in anim)
        am = Image.new("RGBA", (mx * (16 * A + 4) + 114, len(anim) * (16 * A + 4) + 4), (0x8B, 0x8B, 0x8B, 255))
        d2 = ImageDraw.Draw(am)
        for r, (n, fr) in enumerate(anim):
            d2.text((4, 4 + r * (16 * A + 4) + 24), n, fill=(20, 20, 20, 255))
            for c, im in enumerate(fr):
                am.alpha_composite(im.resize((16 * A, 16 * A), Image.NEAREST), (110 + c * (16 * A + 4), 4 + r * (16 * A + 4)))
        am.save(f"{out_dir}/item_art_anim.png")
    return len(items)


