# ============================================================== colour helpers


def hexc(s: str) -> tuple[int, int, int]:
    s = s.lstrip("#")
    return int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16)


def mix(a, b, t: float):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def ramp(*hexes: str) -> list[tuple[int, int, int]]:
    return [hexc(h) for h in hexes]


# ============================================================== canvas


class Canvas:
    """A 16x16 grid of RGB tuples (None = transparent)."""

    def __init__(self, size: int = 16):
        self.n = size
        self.px: list[list] = [[None] * size for _ in range(size)]

    def copy(self) -> "Canvas":
        c = Canvas(self.n)
        c.px = [row[:] for row in self.px]
        return c

    def inside(self, x, y) -> bool:
        return 0 <= x < self.n and 0 <= y < self.n

    def get(self, x, y):
        return self.px[y][x] if self.inside(x, y) else None

    def put(self, x, y, c):
        if self.inside(x, y):
            self.px[y][x] = c

    def image(self) -> Image.Image:
        img = Image.new("RGBA", (self.n, self.n), (0, 0, 0, 0))
        p = img.load()
        for y in range(self.n):
            for x in range(self.n):
                c = self.px[y][x]
                if c is not None:
                    p[x, y] = (c[0], c[1], c[2], 255)
        return img


def grid(text: str) -> list[str]:
    """Normalise an ASCII block: strip indentation, pad rows to equal width."""
    lines = [ln.strip() for ln in text.strip("\n").splitlines()]
    lines = [ln for ln in lines if ln]
    w = max(len(ln) for ln in lines)
    return [ln.ljust(w, ".") for ln in lines]


def blit(cv: Canvas, text: str, colours: dict, ox: int = 0, oy: int = 0):
    for y, row in enumerate(grid(text)):
        for x, ch in enumerate(row):
            if ch in colours:
                cv.put(ox + x, oy + y, colours[ch])


N4 = ((1, 0), (-1, 0), (0, 1), (0, -1))
LIGHT = (-1 / math.sqrt(2), -1 / math.sqrt(2))   # light from the top-left


