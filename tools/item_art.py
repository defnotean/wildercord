"""Hand-tuned 16x16 item art for Wildercord (runes, cords, the cord slot hint).

Everything is data-driven:
  * stones are built from ASCII silhouettes, split into rings (outline, trim /
    facets, face) and lit from the top-left like vanilla items;
  * pictograms are small ASCII grids painted with the family's glow ramp;
  * cords are a shared ASCII loop painted with per-material rules, plus a
    hand-drawn pendant per tier.

Public API (imported by generate_assets.py):
    ANIMATION_FRAMETIME
    rune_icon(path, family, element, tier) -> list[Image]
    blank_rune_icon() -> list[Image]
    silent_rune_icon() -> list[Image]
    cord_icon(key) -> list[Image]
    cord_slot_icon() -> Image
    mana_crystal_icon() -> list[Image]      (16x16, animated)
    clarity_effect_icon() -> Image          (18x18 mob-effect icon)
    mana_effect_icon() -> Image             (18x18 mob-effect icon)
    mana_badge_icon() -> Image              (12x12 GUI badge for a dark screen)
    heart_badge_icon() -> Image             (12x12 GUI badge for a dark screen)
    warded_effect_icon() -> Image           (18x18 mob-effect icon)
    ward_badge_icon() -> Image              (12x12 GUI badge for a dark screen)

Run this file directly to render review contact sheets into build/art-preview (or a folder you pass).
"""
