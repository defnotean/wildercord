def _shimmer(cv: Canvas, stone: Stone, lit: set, frame: int):
    """A diagonal glint that sweeps across the stone during the first half of the loop."""
    sweep = ANIM_FRAMES // 2
    if frame >= sweep:
        return
    centre = 1 + frame * (30 / (sweep - 1))
    for (x, y) in stone.rim | stone.face:
        if (x, y) in lit:
            continue
        k = x + y
        if abs(k - centre) <= 1.0:
            base = cv.get(x, y)
            amt = 0.5 if (x, y) in stone.rim else 0.2
            cv.put(x, y, mix(base, stone.glow[3], amt))


def _render_rune(path, family, element, tier, frame=0) -> Canvas:
    stone = family_stone(family, element)
    cv = stone.canvas.copy()
    text = GLYPHS.get(path, FALLBACK_GLYPH)
    boost = 0.0
    if tier >= 4:
        boost = 0.5 - 0.5 * math.cos(2 * math.pi * frame / ANIM_FRAMES)
    lit = paint_glyph(cv, text, stone.glow, stone.box, boost=boost, safe=stone.safe)
    if tier >= 3:
        _shimmer(cv, stone, lit, frame)
    for p in PIPS.get(family, PIPS["shape"]).get(max(1, min(4, tier)), []):
        cv.put(*p, stone.glow[3] if tier >= 3 else stone.glow[2])
    return cv


