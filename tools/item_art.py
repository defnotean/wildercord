# shared loop: O = outer strand pixel, I = inner strand pixel
LOOP = """
    .....OOOOOO.....
    ...OOIIIIIIOO...
    ..OII......IIO..
    .OI..........IO.
    .OI..........IO.
    .OI..........IO.
    ..OI........IO..
    ...OI......IO...
    ....OI....IO....
    .....OI..IO.....
    ......OIIO......
"""


def loop_cells():
    """Loop pixels in path order, each tagged (x, y, layer, lit)."""
    cells = []
    for y, row in enumerate(grid(LOOP)):
        for x, ch in enumerate(row):
            if ch in "OI":
                cells.append((x, y, ch))
    cx, cy = 7.5, 5.0

    def param(c):
        a = math.atan2(c[1] - cy, c[0] - cx)
        return a if a >= math.pi / 2 else a + 2 * math.pi

    cells.sort(key=param)
    out = []
    for x, y, ch in cells:
        left = x <= 7
        top = y <= 1
        lit = (ch == "O") if (left or top) else (ch == "I")
        out.append((x, y, ch, lit))
    return out


def _twine(cv: Canvas, frame: int):
    L, m, d, X = hexc("#E8D6A8"), hexc("#C6A672"), hexc("#8E6C40"), hexc("#664A2A")
    outer = [c for c in loop_cells() if c[2] == "O"]
    order = {(c[0], c[1]): i for i, c in enumerate(outer)}
    for x, y, layer, lit in loop_cells():
        if layer == "O":
            i = order[(x, y)]
            col = (L if i % 3 else m) if lit else (d if i % 3 else X)   # braid twist every 3rd
        else:
            col = m if lit else d
        cv.put(x, y, col)
    pend = """
        ..mx..
        ..hb..
        .hBbn.
        .Bbnn.
        ..nn..
    """
    blit(cv, pend, {"m": m, "x": X, "h": hexc("#E6B47A"), "B": hexc("#B87A44"),
                    "b": hexc("#915A2E"), "n": hexc("#613A1A")}, 5, 10)


def _copper(cv: Canvas, frame: int):
    L, M, D, X = hexc("#F4A07A"), hexc("#D0683E"), hexc("#94432A"), hexc("#5E2A1A")
    V, v = hexc("#6CC8A4"), hexc("#3C8C72")
    outer = [c for c in loop_cells() if c[2] == "O"]
    order = {(c[0], c[1]): i for i, c in enumerate(outer)}
    verdigris = {5, 6, 17, 18}
    for x, y, layer, lit in loop_cells():
        near = min(order, key=lambda p: abs(p[0] - x) + abs(p[1] - y))
        i = order[near]
        gap = i % 3 == 2
        if i in verdigris:
            col = v if gap else (V if lit else v)
        elif gap:
            col = D if lit else X
        else:
            col = L if lit else M
        cv.put(x, y, col)
    # a little runestone set in a copper bezel
    pend = """
        ..LM..
        .LMMD.
        LksskD
        MsSSsX
        MksskX
        .DXvX.
    """
    blit(cv, pend, {"L": L, "M": M, "D": D, "X": X, "v": v, "k": hexc("#22282E"),
                    "s": hexc("#2A7470"), "S": hexc("#7AF4E4")}, 5, 10)


