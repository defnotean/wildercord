FALLBACK_GLYPH = """
    ...#...
    ..#+#..
    .#.#.#.
    #..*..#
    .#.#.#.
    ..#+#..
    ...#...
"""


def glyph_cells(text: str, box=(4, 9)):
    """Yield (x, y, ch) for a pictogram centred on column 8 and vertically inside
    box = (top row, row count)."""
    g = grid(text)
    h, w = len(g), len(g[0])
    ox = 8 - w // 2
    oy = box[0] + (box[1] - h) // 2
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch != ".":
                yield ox + x, oy + y, ch


def paint_glyph(cv: Canvas, text: str, glow, box=(4, 9), boost: float = 0.0, safe=None) -> set:
    """Paint a pictogram; boost (0..1) brightens every tone one step toward the next."""
    shade, main, light, core = glow
    tone = {
        "-": mix(shade, main, boost * 0.6),
        "#": mix(main, light, boost * 0.6),
        "+": mix(light, core, boost * 0.6),
        "*": core,
    }
    lit = set()
    for x, y, ch in glyph_cells(text, box):
        if safe is not None and (x, y) not in safe:
            continue
        if ch == "o":
            base = cv.get(x, y)
            if base is not None:
                cv.put(x, y, mix(base, (0, 0, 0), 0.5))
            continue
        col = tone.get(ch) or EXTRA.get(ch)
        if col is not None:
            cv.put(x, y, col)
            lit.add((x, y))
    return lit


